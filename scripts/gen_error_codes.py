"""Builds app/core/errors/codes.py from the frontend's shared/utils/errors/codes.ts (status, message)
and docs/ERROR-CODES.md (level).

    fmly\\Scripts\\python.exe scripts\\gen_error_codes.py [path\\to\\formalieFrontend]

The frontend is only read, never changed. tests/parity/test_error_codes.py checks the result.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FRONTEND = Path(os.environ.get("FORMALIE_FRONTEND_DIR", r"C:\UNETPROJECTS\formalieFrontend"))
OUTPUT = ROOT / "app" / "core" / "errors" / "codes.py"

_ENTRY = re.compile(
    r"'(?P<code>FRM-[A-Z]+-\d{4})':\s*\{\s*status:\s*(?P<status>\d{3}),\s*message:\s*(?P<q>['\"])(?P<message>.*?)(?P=q),?\s*\}",
    re.DOTALL,
)
_DOC_ROW = re.compile(r"^\|\s*(FRM-[A-Z]+-\d{4})\s*\|\s*(\d{3})\s*\|.*\|\s*([A-Z]+)\s*\|\s*$")
LEVELS = {"DEBUG", "INFO", "NOTICE", "WARNING", "ERROR", "CRITICAL"}


def parse_codes_ts(path: Path) -> dict[str, tuple[int, str]]:
    text = path.read_text(encoding="utf-8")
    codes: dict[str, tuple[int, str]] = {}
    for match in _ENTRY.finditer(text):
        message = match["message"].replace("\\'", "'").replace('\\"', '"')
        codes[match["code"]] = (int(match["status"]), message)
    return codes


def parse_levels(path: Path) -> dict[str, tuple[int, str]]:
    levels: dict[str, tuple[int, str]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _DOC_ROW.match(line)
        if match:
            levels[match[1]] = (int(match[2]), match[3])
    return levels


def build(frontend: Path) -> str:
    codes = parse_codes_ts(frontend / "shared" / "utils" / "errors" / "codes.ts")
    levels = parse_levels(ROOT / "docs" / "ERROR-CODES.md")
    problems = []
    for code, (status, _) in codes.items():
        if code not in levels:
            problems.append(f"{code}: missing from ERROR-CODES.md")
        elif levels[code][0] != status:
            problems.append(f"{code}: HTTP {status} in codes.ts but {levels[code][0]} in ERROR-CODES.md")
        elif levels[code][1] not in LEVELS:
            problems.append(f"{code}: unknown level {levels[code][1]}")
    if problems:
        raise SystemExit("Fix these first:\n  " + "\n  ".join(problems))

    lines = [
        '"""Every FRM-* code the server sends. GENERATED by scripts/gen_error_codes.py, do not edit by hand.',
        "",
        "Status and message: the frontend's shared/utils/errors/codes.ts. Level: docs/ERROR-CODES.md.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class ErrorDef(NamedTuple):",
        "    status: int",
        "    message: str",
        "    level: str",
        "",
        "",
        "ERROR_CODES: dict[str, ErrorDef] = {",
    ]
    for code, (status, message) in codes.items():
        lines.append(f"    {code!r}: ErrorDef({status}, {message!r}, {levels[code][1]!r}),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    frontend = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_FRONTEND
    OUTPUT.write_text(build(frontend), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
