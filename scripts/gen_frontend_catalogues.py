"""Builds the Python catalogues from tests/vectors/frontend_rules.json (made by scripts/dump_frontend_rules.py):

    app/modules/rbac/catalogue.py    permission areas, actions, scopes, built-in roles, default grants, needs
    app/modules/audit/events.py      every audit action key with its area and icon
    app/modules/billing/plans.py     the plans with prices, limits and features

    fmly\\Scripts\\python.exe scripts\\gen_frontend_catalogues.py

Data only; the logic that uses it is ported by hand and held to the recorded answers by the parity tests.
"""

from __future__ import annotations

import json
import pprint
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = json.loads((ROOT / "tests" / "vectors" / "frontend_rules.json").read_text(encoding="utf-8"))
HEADER = '"""{doc} GENERATED by scripts/gen_frontend_catalogues.py from the frontend\'s {source}; do not edit."""\n\nfrom __future__ import annotations\n\n'


def literal(name: str, value: object) -> str:
    return f"{name} = {pprint.pformat(value, width=110, sort_dicts=False)}\n\n"


def write(path: str, doc: str, source: str, parts: list[tuple[str, object]]) -> None:
    body = HEADER.format(doc=doc, source=source) + "".join(literal(n, v) for n, v in parts)
    (ROOT / path).write_text(body.rstrip("\n") + "\n", encoding="utf-8")
    print(f"Wrote {path}")


def main() -> None:
    r = RULES
    areas = [{"key": a["key"], "groups": [{"key": g["key"], "actions": [
        {"key": x["key"], "scopes": x.get("scopes")} for x in g["actions"]]} for g in a["groups"]]}
        for a in r["permission_areas"]]
    write("app/modules/rbac/catalogue.py", "The permission catalogue (Roles & access, F22).",
          "shared/utils/auth/permissions.ts", [
              ("SCOPES", tuple(r["scopes"])),
              ("PERMISSION_AREAS", areas),
              ("ALL_PERMISSIONS", tuple(r["all_permissions"])),
              ("BUILT_IN_ROLES", tuple(r["built_in_roles"])),
              ("BUILT_IN_ROLE_TEXT", r["built_in_role_text"]),
              ("DEFAULT_ROLE_GRANTS", r["default_role_grants"]),
              ("PERMISSION_NEEDS", r["permission_needs"]),
              ("RESOURCE_VIEWS", tuple(r["resource_views"])),
              ("RESOURCE_CHANGES", tuple(r["resource_changes"])),
              ("SPLIT_PERMISSIONS", r["split_permissions"]),
          ])
    write("app/modules/audit/events.py", "The audit event catalogue: every action key, its area and icon.",
          "shared/utils/audit/events.ts", [
              ("AUDIT_AREAS", tuple(r["audit_areas"])),
              ("AUDIT_EVENTS", r["audit_events"]),
          ])
    write("app/core/locales.py", "The 20 portal and form languages.", "shared/utils/i18n/locales.ts", [
        ("APP_LOCALES", r["app_locales"]),
        ("APP_LOCALE_CODES", tuple(item["code"] for item in r["app_locales"])),
    ])
    write("app/modules/billing/plans.py", "The plans: prices per period, limits and features.",
          "shared/utils/billing/plans.ts", [
              ("PLANS", r["plans"]),
              ("PERIOD_MONTHS", r["period_months"]),
              ("PERIOD_DISCOUNT", r["period_discount"]),
          ])


def settings_catalogues() -> None:
    path = ROOT / "tests" / "vectors" / "settings_rules.json"
    if not path.exists():
        return
    r = json.loads(path.read_text(encoding="utf-8"))
    write("app/modules/settings/catalogues.py", "What the workspace settings choose from.",
          "shared/types (onboarding, appearance, emails, notifications, privacy, settings) and utils/platform/countries", [
              ("SETTINGS_SECTIONS", tuple(r["settings_sections"])),
              ("INDUSTRIES", tuple(r["industries"])),
              ("COMPANY_SIZES", tuple(r["company_sizes"])),
              ("DATE_FORMATS", tuple(r["date_formats"])),
              ("NUMBER_FORMATS", tuple(r["number_formats"])),
              ("APPEARANCE_PRIMARIES", tuple(r["appearance_primaries"])),
              ("APPEARANCE_NEUTRALS", tuple(r["appearance_neutrals"])),
              ("APPEARANCE_RADII", tuple(r["appearance_radii"])),
              ("APPEARANCE_FONTS", tuple(r["appearance_fonts"])),
              ("FORMALIE_APPEARANCE", r["formalie_appearance"]),
              ("EMAIL_TEMPLATES", tuple(r["email_templates"])),
              ("NOTIFICATION_EVENTS", tuple(r["notification_events"])),
              ("RETENTION_DAYS", tuple(r["retention_days"])),
              ("IDLE_MINUTES", tuple(r["idle_minutes"])),
              ("MAX_SESSION_HOURS", tuple(r["max_session_hours"])),
              ("COUNTRY_CURRENCIES", r["country_currencies"]),
              ("CURRENCY_CODES", tuple(r["currency_codes"])),
          ])


if __name__ == "__main__":
    main()
    settings_catalogues()
