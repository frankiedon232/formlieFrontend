def _parsed_json(value: Any) -> Any:
    if not isinstance(value, str):
        return value

    def refuse(_: str) -> Any:
        raise ValueError
    try:
        return json.loads(value, parse_constant=refuse)
    except ValueError:
        return value


def json_export(columns: list[dict[str, Any]], rows: list[dict[str, Any]]) -> str:
    out = []
    for row in rows:
        item = {}
        for c in columns:
            value = row.get(c["name"])
            value = None if js.nullish(value) else value
            item[c["name"]] = _parsed_json(value) if value is not None and kind_of_type(c["type"]) == "json" else value
        out.append(item)
    return f"{js.stringify_pretty(out)}\n"


def _string_literal(engine: str, text: str) -> str:
    escaped = (text.replace("\\", "\\\\") if engine in ("mysql", "mariadb") else text).replace("'", "''")
    return f"{'N' if engine == 'sqlserver' else ''}'{escaped}'"


_ZONE = re.compile(r"Z\Z|[+-][0-9]{2}:[0-9]{2}\Z")


def _plain_date_time(text: str) -> str:
    return _ZONE.sub("", text.replace("T", " ", 1), count=1)


def sql_literal(engine: str, type_: str, value: Any) -> str:
    if js.nullish(value):
        return "NULL"
    kind = kind_of_type(type_)
    if kind in ("integer", "decimal"):
        number = js.to_number(value)
        return js.number_to_string(number) if number == number and number not in (float("inf"), float("-inf")) else "NULL"
    if kind == "boolean":
        yes = value is True or (isinstance(value, (int, float)) and not isinstance(value, bool) and value == 1) \
            or value == "1" or js.to_string(value).lower() == "true"
        return ("TRUE" if yes else "FALSE") if engine == "postgresql" else ("1" if yes else "0")
    if kind == "date":
        text = js.utf16_slice(js.to_string(value), 10)
        return f"DATE '{text}'" if engine == "oracle" else f"'{text}'"
    if kind == "datetime":
        text = _plain_date_time(js.to_string(value))
        return f"TIMESTAMP '{text}'" if engine == "oracle" else f"'{text}'"
    if kind == "json":
        return _string_literal(engine, value if isinstance(value, str) else js.stringify(value))
    return _string_literal(engine, js.stringify(value) if isinstance(value, (dict, list)) else js.to_string(value))


def iso_now(moment: datetime | None = None) -> str:
    return (moment or datetime.now(UTC)).astimezone(UTC).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def sql_insert_script(engine: str, target: dict[str, str], columns: list[dict[str, Any]], rows: list[dict[str, Any]],
                      made_at: str | None = None) -> str:
    table = f"{quote_name(engine, target['schema'])}.{quote_name(engine, target['table'])}"
    names = ", ".join(quote_name(engine, c["name"]) for c in columns)
    identity = engine == "sqlserver" and any(c.get("primary") and c.get("has_default") and kind_of_type(c["type"]) == "integer"
                                            for c in columns)
    begin = {"postgresql": "BEGIN;", "mysql": "START TRANSACTION;", "mariadb": "START TRANSACTION;",
             "sqlserver": "BEGIN TRANSACTION;", "oracle": None}[engine]
    lines = [f"-- {target['schema']}.{target['table']}: {len(rows)} row(s)", f"-- Exported from Formalie on {made_at or iso_now()}", ""]
    if begin:
        lines.append(begin)
    if identity:
        lines.append(f"SET IDENTITY_INSERT {table} ON;")
    for row in rows:
        values = ", ".join(sql_literal(engine, c["type"], row.get(c["name"], js.UNDEFINED)) for c in columns)
        lines.append(f"INSERT INTO {table} ({names}) VALUES ({values});")
    if identity:
        lines.append(f"SET IDENTITY_INSERT {table} OFF;")
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"
