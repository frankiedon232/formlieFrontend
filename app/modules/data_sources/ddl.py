"""Changing the structure of the organisation's own tables from the explorer (shared/utils/datasources/ddl.ts): create
a table, add / change / delete a column, add / delete an index, rename, empty or delete a table. Never response
tables, and only with Full access. The browser shows exactly these statements before anything runs; the server runs
the same ones. Also the export formats (exportFormats.ts): JSON, SQL literals and the INSERT script.
Same answers as the frontend (tests/parity/test_sql_rules.py).
"""

from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from typing import Any

from app.core import js
from app.modules.data_sources.tables import MAX_NAME, kind_of_type, length_of, quote_name

COLUMN_KINDS = ("text", "long_text", "integer", "big_integer", "decimal", "boolean", "date", "datetime", "time", "json")
TABLE_PREFIXES = ("formalie_", "fmly_", "form_")
TEXT_LENGTH_DEFAULT = 255
DECIMAL_DEFAULT = {"length": 12, "scale": 2}
EXPORT_MAX_ROWS = 5000


def kinds_for(engine: str) -> list[str]:
    return [k for k in COLUMN_KINDS if not (engine == "oracle" and k == "time")]


def type_for(engine: str, spec: dict[str, Any]) -> str:
    length = spec.get("length") or TEXT_LENGTH_DEFAULT
    digits = spec.get("length") or DECIMAL_DEFAULT["length"]
    scale = spec.get("scale") if spec.get("scale") is not None else DECIMAL_DEFAULT["scale"]
    length, digits, scale = js.to_string(length), js.to_string(digits), js.to_string(scale)
    mysql = engine in ("mysql", "mariadb")
    kind = spec["kind"]
    if kind == "text":
        return f"NVARCHAR({length})" if engine == "sqlserver" else f"VARCHAR2({length})" if engine == "oracle" else f"VARCHAR({length})"
    if kind == "long_text":
        return "NVARCHAR(MAX)" if engine == "sqlserver" else "CLOB" if engine == "oracle" else "TEXT"
    if kind == "integer":
        return "NUMBER(10)" if engine == "oracle" else "INTEGER" if engine == "postgresql" else "INT"
    if kind == "big_integer":
        return "NUMBER(19)" if engine == "oracle" else "BIGINT"
    if kind == "decimal":
        return f"NUMBER({digits},{scale})" if engine == "oracle" else f"NUMERIC({digits},{scale})" if engine == "postgresql" \
            else f"DECIMAL({digits},{scale})"
    if kind == "boolean":
        return "BOOLEAN" if engine == "postgresql" else "TINYINT(1)" if mysql else "BIT" if engine == "sqlserver" else "NUMBER(1)"
    if kind == "date":
        return "DATE"
    if kind == "datetime":
        return "TIMESTAMPTZ" if engine == "postgresql" else "DATETIME" if mysql else "DATETIME2" if engine == "sqlserver" else "TIMESTAMP"
    if kind == "time":
        return "TIME"
    return "JSONB" if engine == "postgresql" else "JSON" if mysql else "NVARCHAR(MAX)" if engine == "sqlserver" else "CLOB"


def spec_of_type(type_: str) -> dict[str, Any]:
    t = type_.upper()
    kind = kind_of_type(type_)
    if kind == "integer":
        return {"kind": "big_integer" if re.search(r"BIGINT|NUMBER\(19\)", t) else "integer"}
    if kind == "decimal":
        match = re.search(r"\(([0-9]+)[\s]*,[\s]*([0-9]+)\)", t)
        return {"kind": "decimal", "length": int(match.group(1)) if match else None, "scale": int(match.group(2)) if match else None}
    if kind == "text":
        length = length_of(type_)
        return {"kind": "text", "length": length} if length else {"kind": "long_text"}
    return {"kind": kind}


def check_name(engine: str, name: str, what: str) -> str | None:
    """required · chars · long · prefix (tables only)."""
    if not name:
        return "required"
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
        return "chars"
    if len(name) > MAX_NAME[engine]:
        return "long"
    if what == "table" and any(name.lower().startswith(p) for p in TABLE_PREFIXES):
        return "prefix"
    return None


def normalise_db_name(engine: str, text: str) -> str:
    joined = re.sub(f"[{js._WS}]+", "_", js.trim(text))
    return joined.upper() if engine == "oracle" else joined.lower()


def _table_ref(engine: str, schema: str, table: str) -> str:
    return f"{quote_name(engine, schema)}.{quote_name(engine, table)}"


def _default_name(table: str, column: str) -> str:
    return f"DF_{table}_{column}"


def _literal_of(engine: str, spec: dict[str, Any]) -> str:
    return sql_literal(engine, type_for(engine, spec), spec.get("default"))


def _auto(spec: dict[str, Any]) -> bool:
    return bool(spec.get("auto") and spec.get("primary") and spec["kind"] in ("integer", "big_integer"))


def column_sql(engine: str, table: str, spec: dict[str, Any]) -> str:
    parts = [quote_name(engine, spec["name"]), type_for(engine, spec)]
    auto = _auto(spec)
    if auto:
        parts.append({"postgresql": "GENERATED BY DEFAULT AS IDENTITY", "oracle": "GENERATED BY DEFAULT AS IDENTITY",
                      "sqlserver": "IDENTITY(1,1)", "mysql": "", "mariadb": ""}[engine])
    if not auto and spec.get("default"):
        literal = _literal_of(engine, spec)
        parts.append(f"CONSTRAINT {quote_name(engine, _default_name(table, spec['name']))} DEFAULT {literal}"
                     if engine == "sqlserver" else f"DEFAULT {literal}")
    if not spec.get("nullable") or spec.get("primary"):
        parts.append("NOT NULL")
    if auto and engine in ("mysql", "mariadb"):
        parts.append("AUTO_INCREMENT")
    return " ".join(p for p in parts if p)


def create_table_statements(engine: str, schema: str, table: str, columns: list[dict[str, Any]]) -> list[str]:
    primary = [c for c in columns if c.get("primary")]
    lines = [f"  {column_sql(engine, table, c)}" for c in columns]
    if primary:
        keys = ", ".join(quote_name(engine, c["name"]) for c in primary)
        lines.append(f"  CONSTRAINT {quote_name(engine, f'{table}_pk')} PRIMARY KEY ({keys})")
    body = ",\n".join(lines)
    return [f"CREATE TABLE {_table_ref(engine, schema, table)} (\n{body}\n);"]


def change_statements(engine: str, schema: str, table: str, change: dict[str, Any],
                      current: dict[str, Any] | None = None) -> list[str]:
    ref = _table_ref(engine, schema, table)

    def q(name: str) -> str:
        return quote_name(engine, name)
    mysql = engine in ("mysql", "mariadb")
    op = change["op"]
    if op == "add_column":
        column = column_sql(engine, table, change["column"])
        if engine == "oracle":
            return [f"ALTER TABLE {ref} ADD ({column});"]
        if engine == "sqlserver":
            return [f"ALTER TABLE {ref} ADD {column};"]
        return [f"ALTER TABLE {ref} ADD COLUMN {column};"]
    if op == "drop_column":
        return [f"ALTER TABLE {ref} DROP COLUMN {q(change['column'])};"]
    if op == "rename_table":
        if engine == "sqlserver":
            return [f"EXEC sp_rename N'{schema}.{table}', N'{change['name']}';"]
        if mysql:
            return [f"RENAME TABLE {ref} TO {_table_ref(engine, schema, change['name'])};"]
        return [f"ALTER TABLE {ref} RENAME TO {q(change['name'])};"]
    if op == "add_index":
        cols = ", ".join(q(c) for c in change["columns"])
        return [f"CREATE {'UNIQUE ' if change['unique'] else ''}INDEX {q(change['name'])} ON {ref} ({cols});"]
    if op == "drop_index":
        return [f"DROP INDEX {q(change['name'])} ON {ref};" if mysql or engine == "sqlserver"
                else f"DROP INDEX {q(schema)}.{q(change['name'])};"]
    if op == "truncate":
        return [f"TRUNCATE TABLE {ref};"]
    if op == "drop_table":
        return [f"DROP TABLE {ref};"]
    return _alter_column(engine, schema, table, change["column"], change["to"], current)


def _alter_column(engine: str, schema: str, table: str, name: str, to: dict[str, Any], current: dict[str, Any] | None) -> list[str]:
    ref = _table_ref(engine, schema, table)

    def q(value: str) -> str:
        return quote_name(engine, value)
    out: list[str] = []
    if to["name"] != name:
        out.append(f"EXEC sp_rename N'{schema}.{table}.{name}', N'{to['name']}', N'COLUMN';" if engine == "sqlserver"
                   else f"ALTER TABLE {ref} RENAME COLUMN {q(name)} TO {q(to['name'])};")
    column = q(to["name"])
    type_ = type_for(engine, to)
    type_changed = current is None or re.sub(f"[{js._WS}]", "", current["type"]).upper() != type_.upper()
    null_changed = current is None or current["nullable"] != to["nullable"]
    new_default = _literal_of(engine, to) if to.get("default") else None
    default_changed = current is None or (current.get("default") or "") != (to.get("default") or "")
    if not type_changed and not null_changed and not default_changed:
        return out
    if engine == "postgresql":
        if type_changed:
            out.append(f"ALTER TABLE {ref} ALTER COLUMN {column} TYPE {type_} USING {column}::{type_};")
        if null_changed:
            out.append(f"ALTER TABLE {ref} ALTER COLUMN {column} {'DROP' if to['nullable'] else 'SET'} NOT NULL;")
        if default_changed:
            out.append(f"ALTER TABLE {ref} ALTER COLUMN {column} SET DEFAULT {new_default};" if new_default
                       else f"ALTER TABLE {ref} ALTER COLUMN {column} DROP DEFAULT;")
    elif engine in ("mysql", "mariadb"):
        out.append(f"ALTER TABLE {ref} MODIFY COLUMN {column} {type_}{f' DEFAULT {new_default}' if new_default else ''}"
                   f"{' NULL' if to['nullable'] else ' NOT NULL'};")
    elif engine == "sqlserver":
        if type_changed or null_changed:
            out.append(f"ALTER TABLE {ref} ALTER COLUMN {column} {type_}{' NULL' if to['nullable'] else ' NOT NULL'};")
        if default_changed:
            constraint = q(_default_name(table, to["name"]))
            out.append(f"ALTER TABLE {ref} DROP CONSTRAINT IF EXISTS {constraint};")
            if new_default:
                out.append(f"ALTER TABLE {ref} ADD CONSTRAINT {constraint} DEFAULT {new_default} FOR {column};")
    else:
        typed = f" {type_}" if type_changed else ""
        defaulted = f" DEFAULT {new_default if new_default is not None else 'NULL'}" if default_changed else ""
        nulled = (" NULL" if to["nullable"] else " NOT NULL") if null_changed else ""
        out.append(f"ALTER TABLE {ref} MODIFY ({column}{typed}{defaulted}{nulled});")
    return out


def type_change_risky(from_type: str, to: dict[str, Any]) -> bool:
    before = spec_of_type(from_type)
    if before["kind"] == to["kind"]:
        if to["kind"] == "text":
            return (to.get("length") if to.get("length") is not None else TEXT_LENGTH_DEFAULT) < (before.get("length") or 0)
        if to["kind"] == "decimal":
            return (to.get("length") or 0) < (before.get("length") or 0) or (to.get("scale") or 0) < (before.get("scale") or 0)
        return False
    widening = {"integer": ["big_integer", "decimal", "text", "long_text"], "big_integer": ["decimal", "text", "long_text"],
                "text": ["long_text"], "decimal": ["text", "long_text"], "date": ["datetime", "text", "long_text"],
                "boolean": ["integer", "big_integer", "text"]}
    return to["kind"] not in widening.get(before["kind"], [])


