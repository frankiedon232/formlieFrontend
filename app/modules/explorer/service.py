async def _details(c: Connection, engine: str, schema: str, table: str) -> dict[str, Any]:
    """Defaults, indexes and foreign keys of one table, from the catalogue."""
    p1, p2 = c.p(1), c.p(2)
    if engine == "postgresql":
        defaults = await c.fetch("""
            SELECT a.attname AS col, CASE WHEN a.attidentity <> '' THEN 'generated by default as identity'
                   ELSE pg_get_expr(d.adbin, d.adrelid) END AS def
              FROM pg_attribute a JOIN pg_class t ON t.oid = a.attrelid JOIN pg_namespace n ON n.oid = t.relnamespace
              LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
             WHERE n.nspname = $1 AND t.relname = $2 AND a.attnum > 0 AND NOT a.attisdropped""", [schema, table])
        indexes = await c.fetch("""
            SELECT i.relname AS name, ix.indisunique AS uq, ix.indisprimary AS pk,
                   ARRAY(SELECT a.attname FROM unnest(ix.indkey) WITH ORDINALITY k(num, o)
                         JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.num ORDER BY k.o) AS cols
              FROM pg_index ix JOIN pg_class t ON t.oid = ix.indrelid JOIN pg_class i ON i.oid = ix.indexrelid
              JOIN pg_namespace n ON n.oid = t.relnamespace
             WHERE n.nspname = $1 AND t.relname = $2 ORDER BY ix.indisprimary DESC, i.relname""", [schema, table])
        keys = await c.fetch("""
            SELECT con.conname AS name,
                   ARRAY(SELECT a.attname FROM unnest(con.conkey) WITH ORDINALITY k(num, o)
                         JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.num ORDER BY k.o) AS cols,
                   rn.nspname AS ref_schema, rt.relname AS ref_table,
                   ARRAY(SELECT a.attname FROM unnest(con.confkey) WITH ORDINALITY k(num, o)
                         JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.num ORDER BY k.o) AS ref_cols
              FROM pg_constraint con JOIN pg_class t ON t.oid = con.conrelid JOIN pg_namespace n ON n.oid = t.relnamespace
              JOIN pg_class rt ON rt.oid = con.confrelid JOIN pg_namespace rn ON rn.oid = rt.relnamespace
             WHERE con.contype = 'f' AND n.nspname = $1 AND t.relname = $2 ORDER BY con.conname""", [schema, table])
        return {"defaults": {r["col"]: r["def"] for r in defaults},
                "indexes": [{"name": r["name"], "columns": list(r["cols"]), "unique": bool(r["uq"]), "primary": bool(r["pk"])}
                            for r in indexes],
                "keys": [{"name": r["name"], "columns": list(r["cols"]), "references": {
                    "schema": r["ref_schema"], "table": r["ref_table"], "columns": list(r["ref_cols"])}} for r in keys]}
    if engine in ("mysql", "mariadb"):
        defaults = await c.fetch("SELECT COLUMN_NAME AS col, CASE WHEN EXTRA LIKE '%%auto_increment%%' THEN 'auto increment' "
                                 "ELSE COLUMN_DEFAULT END AS def FROM information_schema.COLUMNS "
                                 f"WHERE TABLE_SCHEMA = {p1} AND TABLE_NAME = {p2}", [schema, table])
        stats = await c.fetch("SELECT INDEX_NAME AS name, NON_UNIQUE AS nu, COLUMN_NAME AS col FROM information_schema.STATISTICS "
                              f"WHERE TABLE_SCHEMA = {p1} AND TABLE_NAME = {p2} ORDER BY INDEX_NAME = 'PRIMARY' DESC, "
                              "INDEX_NAME, SEQ_IN_INDEX", [schema, table])
        keys = await c.fetch("SELECT CONSTRAINT_NAME AS name, COLUMN_NAME AS col, REFERENCED_TABLE_SCHEMA AS rs, "
                             "REFERENCED_TABLE_NAME AS rt, REFERENCED_COLUMN_NAME AS rc FROM information_schema.KEY_COLUMN_USAGE "
                             f"WHERE TABLE_SCHEMA = {p1} AND TABLE_NAME = {p2} AND REFERENCED_TABLE_NAME IS NOT NULL "
                             "ORDER BY CONSTRAINT_NAME, ORDINAL_POSITION", [schema, table])
        indexes: dict[str, dict[str, Any]] = {}
        for r in stats:
            item = indexes.setdefault(r["name"], {"name": r["name"], "columns": [], "unique": not int(r["nu"]),
                                                  "primary": r["name"] == "PRIMARY"})
            item["columns"].append(r["col"])
        fks: dict[str, dict[str, Any]] = {}
        for r in keys:
            item = fks.setdefault(r["name"], {"name": r["name"], "columns": [], "references": {
                "schema": r["rs"], "table": r["rt"], "columns": []}})
            item["columns"].append(r["col"])
            item["references"]["columns"].append(r["rc"])
        return {"defaults": {r["col"]: r["def"] for r in defaults}, "indexes": list(indexes.values()), "keys": list(fks.values())}
    if engine == "sqlserver":
        defaults = await c.fetch("""
            SELECT col.name AS col, CASE WHEN col.is_identity = 1 THEN 'auto increment'
                   ELSE OBJECT_DEFINITION(col.default_object_id) END AS def
              FROM sys.columns col JOIN sys.tables t ON t.object_id = col.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
             WHERE s.name = %s AND t.name = %s""", [schema, table])
        stats = await c.fetch("""
            SELECT i.name AS name, i.is_unique AS uq, i.is_primary_key AS pk, col.name AS col
              FROM sys.indexes i JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
              JOIN sys.columns col ON col.object_id = ic.object_id AND col.column_id = ic.column_id
              JOIN sys.tables t ON t.object_id = i.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
             WHERE s.name = %s AND t.name = %s AND i.name IS NOT NULL ORDER BY i.is_primary_key DESC, i.name, ic.key_ordinal""",
                              [schema, table])
        keys = await c.fetch("""
            SELECT fk.name AS name, pc.name AS col, rs.name AS rs, rt.name AS rt, rc.name AS rc
              FROM sys.foreign_keys fk JOIN sys.foreign_key_columns k ON k.constraint_object_id = fk.object_id
              JOIN sys.tables t ON t.object_id = fk.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
              JOIN sys.columns pc ON pc.object_id = k.parent_object_id AND pc.column_id = k.parent_column_id
              JOIN sys.tables rt ON rt.object_id = fk.referenced_object_id JOIN sys.schemas rs ON rs.schema_id = rt.schema_id
              JOIN sys.columns rc ON rc.object_id = k.referenced_object_id AND rc.column_id = k.referenced_column_id
             WHERE s.name = %s AND t.name = %s ORDER BY fk.name, k.constraint_column_id""", [schema, table])
    else:
        defaults = await c.fetch("SELECT column_name AS col, CASE WHEN identity_column = 'YES' THEN 'auto increment' "
                                 "ELSE data_default END AS def FROM all_tab_columns WHERE owner = :1 AND table_name = :2",
                                 [schema, table])
        stats = await c.fetch("""
            SELECT i.index_name AS name, CASE WHEN i.uniqueness = 'UNIQUE' THEN 1 ELSE 0 END AS uq,
                   CASE WHEN EXISTS (SELECT 1 FROM all_constraints k WHERE k.owner = i.table_owner AND k.index_name = i.index_name
                        AND k.constraint_type = 'P') THEN 1 ELSE 0 END AS pk, ic.column_name AS col
              FROM all_indexes i JOIN all_ind_columns ic ON ic.index_owner = i.owner AND ic.index_name = i.index_name
             WHERE i.table_owner = :1 AND i.table_name = :2 ORDER BY 3 DESC, 1, ic.column_position""", [schema, table])
        keys = await c.fetch("""
            SELECT k.constraint_name AS name, cc.column_name AS col, r.owner AS rs, r.table_name AS rt, rc.column_name AS rc
              FROM all_constraints k JOIN all_cons_columns cc ON cc.owner = k.owner AND cc.constraint_name = k.constraint_name
              JOIN all_constraints r ON r.owner = k.r_owner AND r.constraint_name = k.r_constraint_name
              JOIN all_cons_columns rc ON rc.owner = r.owner AND rc.constraint_name = r.constraint_name AND rc.position = cc.position
             WHERE k.constraint_type = 'R' AND k.owner = :1 AND k.table_name = :2 ORDER BY 1, cc.position""", [schema, table])
    indexes = {}
    for r in stats:
        item = indexes.setdefault(r["name"], {"name": r["name"], "columns": [], "unique": bool(r["uq"]), "primary": bool(r["pk"])})
        item["columns"].append(r["col"])
    fks = {}
    for r in keys:
        item = fks.setdefault(r["name"], {"name": r["name"], "columns": [], "references": {"schema": r["rs"], "table": r["rt"],
                                                                                         "columns": []}})
        item["columns"].append(r["col"])
        item["references"]["columns"].append(r["rc"])
    return {"defaults": {r["col"]: (str(r["def"]).strip() if r["def"] is not None else None) for r in defaults},
            "indexes": list(indexes.values()), "keys": list(fks.values())}


def _ddl(engine: str, schema: str, name: str, columns: list[dict[str, Any]], primary: list[str],
         keys: list[dict[str, Any]]) -> str:
    q = T.quote_name
    lines = []
    for col in columns:
        default = col.get("default")
        identity = default in ("generated by default as identity", "auto increment")
        extra = ""
        if identity:
            extra = {"postgresql": " GENERATED BY DEFAULT AS IDENTITY", "oracle": " GENERATED BY DEFAULT AS IDENTITY",
                     "sqlserver": " IDENTITY(1,1)"}.get(engine, "")
        elif default:
            extra = f" DEFAULT {default}"
        tail = " AUTO_INCREMENT" if identity and engine in ("mysql", "mariadb") else ""
        lines.append(f"  {q(engine, col['name'])} {col['type']}{extra}{'' if col['nullable'] else ' NOT NULL'}{tail}")
    if primary:
        lines.append(f"  CONSTRAINT {q(engine, f'{name}_pk')} PRIMARY KEY ({', '.join(q(engine, n) for n in primary)})")
    for key in keys:
        ref = key["references"]
        lines.append(f"  CONSTRAINT {q(engine, key['name'])} FOREIGN KEY ({', '.join(q(engine, n) for n in key['columns'])}) "
                     f"REFERENCES {q(engine, ref['schema'])}.{q(engine, ref['table'])} "
                     f"({', '.join(q(engine, n) for n in ref['columns'])})")
    body = ",\n".join(lines)
    return f"CREATE TABLE {q(engine, schema)}.{q(engine, name)} (\n{body}\n);"


async def structure(c: Connection, source: Any, table: dict[str, Any], destination: Any | None,
                    form: dict[str, str] | None) -> dict[str, Any]:
    """TableStructure (shared/types/explorer.ts)."""
    engine = source.engine
    details = await _details(c, engine, table["schema"], table["name"])
    refs = {}
    for key in details["keys"]:
        if len(key["columns"]) == 1:
            ref = key["references"]
            refs[key["columns"][0]] = {"schema": ref["schema"], "table": ref["table"], "column": ref["columns"][0]}
    columns = [{**col, "default": details["defaults"].get(col["name"]), "references": refs.get(col["name"])}
               for col in table["columns"]]
    primary = next((i["columns"] for i in details["indexes"] if i["primary"]), None) or \
        [col["name"] for col in columns if col["primary"]]
    ddl = T.create_table_sql(engine, table["schema"], table["name"], destination.columns) if destination is not None \
        else _ddl(engine, table["schema"], table["name"], columns, primary, details["keys"])
    access = source.access.get("other")
    read_only = "response_table" if table["formalie"] else "read_access" if access != "read_write" else \
        "no_key" if not primary else None
    return {"schema": table["schema"], "name": table["name"], "kind": "table", "formalie": table["formalie"], "form": form,
            "columns": columns, "primary_key": primary, "indexes": details["indexes"], "foreign_keys": details["keys"],
            "rows_estimate": table["rows_estimate"], "ddl": ddl, "read_only": read_only,
            "alterable": not table["formalie"] and access == "read_write"}


# ── Tables ──────────────────────────────────────────────────────────────────────

async def tables_of(c: Connection, source: Any) -> list[dict[str, Any]]:
    try:
        return await list_tables(c, source.engine, source.settings, source.access)
    except Exception as error:  # noqa: BLE001
        raise _failed(error) from None


def find_table(tables: list[dict[str, Any]], schema: Any, name: Any) -> dict[str, Any]:
    found = next((t for t in tables if t["schema"] == js.to_string(schema or "") and t["name"] == js.to_string(name or "")), None)
    if found is None:
        raise FrmError("FRM-GEN-1004")
    return found


def _failed(error: Exception) -> FrmError:
    problem = error if isinstance(error, WriteError) else refused(error)
    if problem.code == "FRM-DEST-1025":
        return FrmError("FRM-DEST-1025", [{"field": "message", "message": problem.detail[:300] or "error"},
                                          {"field": "position", "message": "0"}])
    return FrmError(problem.code)


