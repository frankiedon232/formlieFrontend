def _where(engine: str, c: Connection, columns: list[dict[str, Any]], q: str, filters: dict[str, str],
           params: list[Any]) -> str:
    """WHERE for the search (any column, case-insensitive) and the filters (`filter[column]=a,b`)."""
    names = {col["name"] for col in columns}
    parts = []
    if q:
        like = "%" + q.lower().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
        ors = []
        for col in columns:
            params.append(like)
            escape = "" if engine in ("mysql", "mariadb") else " ESCAPE '\\'"
            ors.append(f"LOWER({_text(engine, col['name'])}) LIKE {c.p(len(params))}{escape}")
        parts.append("(" + " OR ".join(ors) + ")")
    for column, wanted in filters.items():
        if column not in names or not wanted:
            continue
        marks = []
        for value in wanted.split(","):
            params.append(value)
            marks.append(c.p(len(params)))
        parts.append(f"{_text(engine, column)} IN ({', '.join(marks)})")
    return f" WHERE {' AND '.join(parts)}" if parts else ""


async def rows(c: Connection, engine: str, struct: dict[str, Any], query: dict[str, str], page: int,
               page_size: int) -> tuple[list[dict[str, Any]], int, bool]:
    """One page of rows, the count (up to 10,000) and whether it was capped."""
    columns = struct["columns"]
    names = [col["name"] for col in columns]
    filters = {k[7:-1]: v for k, v in query.items() if k.startswith("filter[") and k.endswith("]")}
    params: list[Any] = []
    where = _where(engine, c, columns, (query.get("q") or "").strip(), filters, params)
    target = T.qualified(engine, struct["schema"], struct["name"])
    sort = query.get("sort") or ""
    order = []
    key = sort.lstrip("-")
    if key in names:
        nulls = " NULLS LAST" if engine in ("postgresql", "oracle") else ""
        if engine in ("mysql", "mariadb", "sqlserver"):
            order.append(f"CASE WHEN {_q(engine, key)} IS NULL THEN 1 ELSE 0 END")
        order.append(f"{_q(engine, key)} {'DESC' if sort.startswith('-') else 'ASC'}{nulls}")
    order += [_q(engine, n) for n in struct["primary_key"] if n != key]  # then the key, so pages are stable
    if not order and engine in ("sqlserver", "oracle"):
        order.append("(SELECT NULL)" if engine == "sqlserver" else "ROWNUM")
    order_by = f" ORDER BY {', '.join(order)}" if order else ""
    listed = ", ".join(_q(engine, n) for n in names)
    try:
        found = await c.fetch(f"SELECT {listed} FROM {target}{where}{order_by}{_page(engine, page_size, (page - 1) * page_size)}",
                              params)
        counted = await c.fetch(_capped(engine, f"SELECT 1 FROM {target}{where}", COUNT_CAP + 1), params)
    except Exception as error:  # noqa: BLE001
        raise _failed(error) from None
    total = int(counted[0]["n"]) if counted else 0
    out = []
    for r in found:
        row = {n: plain(r.get(n) if n in r else r.get(n.lower())) for n in names}
        out.append({**row, "__key": key_of(struct["primary_key"], row)})
    return out, min(total, COUNT_CAP), total > COUNT_CAP


async def facets(c: Connection, engine: str, struct: dict[str, Any]) -> list[dict[str, Any]]:
    """Values of columns with 2 to 12 distinct values (a capped look; a slow column gets no filter)."""
    import re

    target = T.qualified(engine, struct["schema"], struct["name"])
    out = []
    for col in struct["columns"]:
        if col["primary"] or re.search(r"JSON|CLOB|TEXT|MAX|BLOB|BYTEA", col["type"], re.I):
            continue
        text = _text(engine, col["name"])
        sample = f"SELECT {text} AS v FROM {target} WHERE {_q(engine, col['name'])} IS NOT NULL"
        if engine == "sqlserver":
            sample = sample.replace("SELECT ", f"SELECT TOP {FACET_SAMPLE} ", 1)
            sql = f"SELECT TOP 13 v, COUNT(*) AS n FROM ({sample}) x WHERE v <> '' GROUP BY v ORDER BY n DESC"
        elif engine == "oracle":
            sql = (f"SELECT v, COUNT(*) AS n FROM ({sample} FETCH FIRST {FACET_SAMPLE} ROWS ONLY) x WHERE v IS NOT NULL "
                   "GROUP BY v ORDER BY n DESC FETCH FIRST 13 ROWS ONLY")
        else:
            sql = f"SELECT v, COUNT(*) AS n FROM ({sample} LIMIT {FACET_SAMPLE}) x WHERE v <> '' GROUP BY v ORDER BY n DESC LIMIT 13"
        try:
            found = await c.fetch(sql)
        except Exception:  # noqa: BLE001 (over the limit or not comparable: no filter for this column)
            continue
        if 2 <= len(found) <= 12:
            out.append({"column": col["name"], "values": [{"value": str(r["v"]), "count": int(r["n"])} for r in found]})
    return out


# ── Changing rows ───────────────────────────────────────────────────────────────

def typed_row(struct: dict[str, Any], given: dict[str, Any], partial: bool) -> dict[str, Any]:
    """Values for a row checked per column type, or FRM-GEN-1002 with a problem per column."""
    values: dict[str, Any] = {}
    problems = []
    for col in struct["columns"]:
        if partial and (col["name"] not in given or col["primary"]):
            continue
        parsed = T.parse_value(col, given.get(col["name"], js.UNDEFINED))
        if "problem" in parsed:
            problems.append({"field": col["name"], "message": parsed["problem"]})
        else:
            values[col["name"]] = parsed["value"]
    if problems:
        raise FrmError("FRM-GEN-1002", problems)
    return values


def _key_values(struct: dict[str, Any], key: str) -> list[tuple[str, str]]:
    parts = key.split("|")
    if len(parts) != len(struct["primary_key"]):
        raise FrmError("FRM-GEN-1004")
    return list(zip(struct["primary_key"], parts, strict=True))


def _types(struct: dict[str, Any]) -> dict[str, str]:
    return {col["name"]: col["type"] for col in struct["columns"]}


async def _row_by_key(c: Connection, engine: str, struct: dict[str, Any], pairs: list[tuple[str, Any]]) -> dict[str, Any] | None:
    types = _types(struct)
    params = [bound(engine, types[n], v) for n, v in pairs]
    where = " AND ".join(f"{_q(engine, n)} = {c.p(i + 1)}" for i, (n, _) in enumerate(pairs))
    listed = ", ".join(_q(engine, col["name"]) for col in struct["columns"])
    found = await c.fetch(f"SELECT {listed} FROM {T.qualified(engine, struct['schema'], struct['name'])} WHERE {where}", params)
    if not found:
        return None
    row = {col["name"]: plain(found[0].get(col["name"], found[0].get(col["name"].lower()))) for col in struct["columns"]}
    return {**row, "__key": key_of(struct["primary_key"], row)}


async def insert_row(c: Connection, engine: str, struct: dict[str, Any], values: dict[str, Any]) -> dict[str, Any]:
    by_name = {col["name"]: col for col in struct["columns"]}
    # An empty auto-numbered (or defaulted) column is left to the database
    given = {n: v for n, v in values.items() if not (v is None and by_name[n]["has_default"])}
    pairs = [(n, given.get(n)) for n in struct["primary_key"]]
    if all(v is not None for _, v in pairs) and await _row_by_key(c, engine, struct, pairs):
        raise FrmError("FRM-DEST-1018", [{"field": struct["primary_key"][0], "message": "taken"}])
    types = _types(struct)
    names = list(given)
    target = T.qualified(engine, struct["schema"], struct["name"])
    params = [bound(engine, types[n], given[n]) for n in names]
    marks = ", ".join(c.p(i + 1) for i in range(len(names)))
    try:
        if engine == "postgresql":
            listed = ", ".join(_q(engine, col["name"]) for col in struct["columns"])
            found = await c.fetch(f"INSERT INTO {target} ({', '.join(_q(engine, n) for n in names)}) VALUES ({marks}) "
                                  f"RETURNING {listed}", params)
            row = {col["name"]: plain(found[0][col["name"]]) for col in struct["columns"]}
            return {**row, "__key": key_of(struct["primary_key"], row)}
        await c.execute(f"INSERT INTO {target} ({', '.join(_q(engine, n) for n in names)}) VALUES ({marks})" if names
                        else f"INSERT INTO {target} DEFAULT VALUES", params)
    except FrmError:
        raise
    except Exception as error:  # noqa: BLE001
        raise _failed(error) from None
    if any(v is None for _, v in pairs) and engine in ("mysql", "mariadb"):
        last = await c.fetch("SELECT LAST_INSERT_ID() AS id")
        pairs = [(n, v if v is not None else last[0]["id"]) for n, v in pairs]
    found_row = await _row_by_key(c, engine, struct, pairs) if all(v is not None for _, v in pairs) else None
    return found_row or {**{n: plain(v) for n, v in given.items()}, "__key": key_of(struct["primary_key"], given)}


async def update_row(c: Connection, engine: str, struct: dict[str, Any], key: str, values: dict[str, Any]) -> dict[str, Any]:
    pairs = _key_values(struct, key)
    if await _row_by_key(c, engine, struct, pairs) is None:
        raise FrmError("FRM-GEN-1004")
    types = _types(struct)
    if values:
        names = list(values)
        params = [bound(engine, types[n], values[n]) for n in names] + [bound(engine, types[n], v) for n, v in pairs]
        sets = ", ".join(f"{_q(engine, n)} = {c.p(i + 1)}" for i, n in enumerate(names))
        where = " AND ".join(f"{_q(engine, n)} = {c.p(len(names) + i + 1)}" for i, (n, _) in enumerate(pairs))
        try:
            await c.execute(f"UPDATE {T.qualified(engine, struct['schema'], struct['name'])} SET {sets} WHERE {where}", params)
        except Exception as error:  # noqa: BLE001
            raise _failed(error) from None
    return await _row_by_key(c, engine, struct, pairs) or {}


async def delete_row(c: Connection, engine: str, struct: dict[str, Any], key: str) -> None:
    pairs = _key_values(struct, key)
    if await _row_by_key(c, engine, struct, pairs) is None:
        raise FrmError("FRM-GEN-1004")
    types = _types(struct)
    where = " AND ".join(f"{_q(engine, n)} = {c.p(i + 1)}" for i, (n, _) in enumerate(pairs))
    try:
        await c.execute(f"DELETE FROM {T.qualified(engine, struct['schema'], struct['name'])} WHERE {where}",
                        [bound(engine, types[n], v) for n, v in pairs])
    except Exception as error:  # noqa: BLE001
        raise _failed(error) from None


def own_schema(source: Any) -> str:
    return tables_schema_of(source.engine, source.settings, source.access)
