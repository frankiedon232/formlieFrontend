# ── Values as JSON ──────────────────────────────────────────────────────────────

def plain(value: Any) -> Any:
    """A database value as the browser gets it (dates as ISO text, numbers as numbers, bytes as base64)."""
    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return None if value != value or value in (float("inf"), float("-inf")) else value
    if isinstance(value, Decimal):
        return int(value) if value == value.to_integral_value() and abs(value) < 2**53 else float(value)
    if isinstance(value, datetime):
        if value.tzinfo is None:
            return value.isoformat(timespec="milliseconds")
        return value.astimezone(UTC).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    if isinstance(value, (date, time)):
        return value.isoformat()
    if isinstance(value, timedelta):
        return str(value)
    if isinstance(value, uuid.UUID):
        return str(value)
    if isinstance(value, (bytes, bytearray, memoryview)):
        return base64.b64encode(bytes(value)).decode("ascii")
    if isinstance(value, (list, tuple)):
        return [plain(v) for v in value]
    if isinstance(value, dict):
        return {str(k): plain(v) for k, v in value.items()}
    return js.to_string(value) if not hasattr(value, "read") else None


def key_of(primary: list[str], row: dict[str, Any]) -> str:
    """`__key`: the primary key's values, joined by | (as the mock does)."""
    return "|".join("" if row.get(name) is None else js.to_string(row.get(name)) for name in primary)


# ── The engine's ways ───────────────────────────────────────────────────────────

def _q(engine: str, name: str) -> str:
    return T.quote_name(engine, name)


def _text(engine: str, column: str) -> str:
    """A column as text, for searching and filters."""
    q = _q(engine, column)
    return {"postgresql": f"CAST({q} AS text)", "mysql": f"CAST({q} AS CHAR)", "mariadb": f"CAST({q} AS CHAR)",
            "sqlserver": f"CAST({q} AS NVARCHAR(MAX))", "oracle": f"TO_CHAR({q})"}[engine]


def _page(engine: str, limit: int, offset: int) -> str:
    if engine in ("sqlserver", "oracle"):
        return f" OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY"
    return f" LIMIT {limit} OFFSET {offset}"


def _capped(engine: str, inner: str, cap: int) -> str:
    """SELECT COUNT(*) over at most `cap` rows of `inner` (a SELECT 1 … WHERE …)."""
    if engine == "sqlserver":
        return f"SELECT COUNT(*) AS n FROM ({inner.replace('SELECT 1', f'SELECT TOP {cap} 1', 1)}) x"
    if engine == "oracle":
        return f"SELECT COUNT(*) AS n FROM ({inner} FETCH FIRST {cap} ROWS ONLY) x"
    return f"SELECT COUNT(*) AS n FROM ({inner} LIMIT {cap}) x"


