"""The database explorer (mock: routes/explorer.ts, data/databaseRows.ts; API-CONTRACT → Database explorer): a
table's structure read from the database's own catalogue, its rows one page at a time (paged, sorted, searched and
filtered in the database, counted up to 10,000), the values of low-variety columns, and changing rows.

Never the whole table: one page per query, a capped count, facets from a capped look, a 5 second limit on every
statement. Column names are checked against the table's columns and quoted the engine's way; values are bound.
"""

