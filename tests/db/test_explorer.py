"""The database explorer (B9) against the real "customer" PostgreSQL database: the tree, a table's columns and
structure (keys, indexes, foreign keys, defaults, definition), rows one page at a time (sorted, searched, filtered,
counted), filters, adding / changing / deleting rows, read-only tables, structure changes (create, add / change /
drop a column, indexes, rename, empty, delete), the audit trail and another workspace."""

from __future__ import annotations

import uuid

import pytest

from tests.conftest import client_for
from tests.db.test_auth_flows import app, seeded, sign_in  # noqa: F401  (fixtures)
from tests.db.test_data_sources import customer, on_plan, tests_run  # noqa: F401  (fixture)
from tests.db.test_destinations import customer_db
from tests.db.test_settings import PASSWORD, new_workspace
from tests.secure_client import SecureClient

pytestmark = pytest.mark.db
ACCESS = {"table_prefix": "formalie_", "tables_schema": "", "other": "read_write", "schemas": []}


async def test_explorer_from_start_to_finish(app, owner_dsn, tests_run) -> None:  # noqa: ANN001, F811
    db = customer()
    s = uuid.uuid4().hex[:8]
    teams, people, made, own = f"teams_{s}", f"people_{s}", f"projects_{s}", f"formalie_answers_{s}"
    raw = await customer_db()
    await raw.execute(f'CREATE TABLE public."{teams}" (id INT PRIMARY KEY, name VARCHAR(80) NOT NULL)')
    await raw.execute(f'''CREATE TABLE public."{people}" (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name VARCHAR(100) NOT NULL, email VARCHAR(200), status VARCHAR(16) DEFAULT 'open',
        team_id INT REFERENCES public."{teams}" (id), joined DATE, score NUMERIC(6,2), active BOOLEAN DEFAULT true)''')
    await raw.execute(f'INSERT INTO public."{teams}" VALUES (1, \'Finance\'), (2, \'Support\')')
    for i in range(1, 26):
        await raw.execute(f'INSERT INTO public."{people}" (full_name, email, status, team_id, joined, score) VALUES ($1, $2, $3, $4, $5, $6)',
                          f"Person {i:02d}", f"p{i}@example.com", ("open", "closed")[i % 2], 1 + i % 2,
                          __import__("datetime").date(2026, 1, i), i * 1.5)
    await raw.execute(f'CREATE TABLE public."{own}" (response_id UUID PRIMARY KEY, answer TEXT)')
    await raw.execute(f'ANALYZE public."{people}"')
    sub, email = await new_workspace(app)
    await on_plan(owner_dsn, sub, "business")
    try:
        async with client_for(app, host=f"{sub}.formalie.dev") as http:
            owner = SecureClient(http)
            await sign_in(owner, email, PASSWORD)
            status, reply = await owner.request("POST", "/datasources", body={
                "name": "Cases", "engine": "postgresql", "settings": db["settings"], "access": ACCESS, "secrets": db["secrets"]})
            assert status == 201, reply
            sid = reply["data"]["id"]
            base = f"/datasources/{sid}/explorer"

            # The tree: names only, searched, Formalie's tables first
            _, reply = await owner.request("GET", f"{base}/tables", query={"columns": "none", "q": s})
            assert [t["name"] for t in reply["data"]] == [own, people, teams]
            assert reply["data"][0]["formalie"] is True and reply["data"][1]["columns"] == [] and reply["meta"]["total"] == 3
            _, reply = await owner.request("GET", f"{base}/columns", query={"schema": "public", "table": people})
            assert [c["name"] for c in reply["data"]][:3] == ["id", "full_name", "email"]

            # Structure: keys, indexes, foreign keys, defaults, the definition
            _, reply = await owner.request("GET", f"{base}/structure", query={"schema": "public", "table": people})
            st = reply["data"]
            assert st["primary_key"] == ["id"] and st["read_only"] is None and st["alterable"] is True and st["formalie"] is False
            cols = {c["name"]: c for c in st["columns"]}
            assert cols["id"]["default"] == "generated by default as identity" and cols["status"]["default"].startswith("'open'")
            assert cols["team_id"]["references"] == {"schema": "public", "table": teams, "column": "id"}
            assert st["foreign_keys"][0]["references"]["table"] == teams and st["indexes"][0]["primary"] is True
            assert st["ddl"].startswith(f'CREATE TABLE "public"."{people}" (') and "GENERATED BY DEFAULT AS IDENTITY" in st["ddl"]
            _, reply = await owner.request("GET", f"{base}/structure", query={"schema": "public", "table": own})
            assert reply["data"]["read_only"] == "response_table" and reply["data"]["alterable"] is False

            # Rows: one page, sorted, searched, filtered, counted
            _, reply = await owner.request("GET", f"{base}/rows", query={"schema": "public", "table": people, "page_size": "10",
                                                                        "page": "2", "sort": "-score"})
            assert reply["meta"]["total"] == 25 and len(reply["data"]) == 10 and reply["data"][0]["full_name"] == "Person 15"
            assert reply["data"][0]["__key"] == "15" and reply["data"][0]["joined"] == "2026-01-15" and reply["data"][0]["score"] == 22.5
            _, reply = await owner.request("GET", f"{base}/rows", query={"schema": "public", "table": people, "q": "PERSON 0"})
            assert reply["meta"]["total"] == 9
            _, reply = await owner.request("GET", f"{base}/rows", query={"schema": "public", "table": people,
                                                                        "filter[status]": "closed", "filter[team_id]": "2"})
            assert reply["meta"]["total"] == 13 and {r["status"] for r in reply["data"]} == {"closed"}
            _, reply = await owner.request("GET", f"{base}/facets", query={"schema": "public", "table": people})
            facets = {f["column"]: f["values"] for f in reply["data"]}
            assert facets["status"] == [{"value": "closed", "count": 13}, {"value": "open", "count": 12}] and "full_name" not in facets

            # Rows changed: checked per type; the key numbered by the database; a taken key refused
            _, reply = await owner.request("POST", f"{base}/rows", body={"schema": "public", "table": people,
                                                                        "values": {"full_name": "", "score": "lots", "joined": "soon"}})
            assert {d["field"]: d["message"] for d in reply["error"]["details"]} == {"full_name": "required", "score": "number", "joined": "date"}
            status, reply = await owner.request("POST", f"{base}/rows", body={"schema": "public", "table": people,
                                                                             "values": {"full_name": "New Person", "score": "7.25", "active": "no"}})
            assert status == 201, reply
            added = reply["data"]
            assert added["id"] == 26 and added["__key"] == "26" and added["status"] == "open" and added["active"] is False
            _, reply = await owner.request("POST", f"{base}/rows", body={"schema": "public", "table": people,
                                                                        "values": {"id": 26, "full_name": "Again"}})
            assert reply["error"]["code"] == "FRM-DEST-1018"
            _, reply = await owner.request("PATCH", f"{base}/rows", body={"schema": "public", "table": people, "key": "26",
                                                                         "values": {"email": "new@example.com", "id": 99}})
            assert reply["data"]["email"] == "new@example.com" and reply["data"]["id"] == 26
            _, reply = await owner.request("DELETE", f"{base}/rows", query={"schema": "public", "table": people, "key": "26"})
            assert reply["data"] == {"deleted": True}
            _, reply = await owner.request("DELETE", f"{base}/rows", query={"schema": "public", "table": people, "key": "26"})
            assert reply["error"]["code"] == "FRM-GEN-1004"
            _, reply = await owner.request("POST", f"{base}/rows", body={"schema": "public", "table": own, "values": {"answer": "x"}})
            assert reply["error"]["code"] == "FRM-DEST-1019" and reply["error"]["details"][0]["message"] == "response_table"

            # Structure changes on their own tables
            spec = [{"name": "id", "kind": "integer", "nullable": False, "primary": True, "auto": True},
                    {"name": "title", "kind": "text", "length": 120, "nullable": False, "default": "Untitled"}]
            _, reply = await owner.request("POST", f"{base}/tables", body={"schema": "public", "name": "formalie_x", "columns": spec})
            assert reply["error"]["details"] == [{"field": "name", "message": "prefix"}]
            status, reply = await owner.request("POST", f"{base}/tables", body={"schema": "public", "name": made, "columns": spec})
            assert status == 201 and reply["data"]["statements"][0].startswith(f'CREATE TABLE "public"."{made}"')
            _, reply = await owner.request("POST", f"{base}/tables", body={"schema": "public", "name": made, "columns": spec})
            assert reply["error"]["code"] == "FRM-DEST-1022"
            change = f"{base}/changes"
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {
                "op": "add_column", "column": {"name": "budget", "kind": "decimal", "length": 10, "scale": 2, "nullable": True}}})
            assert reply["data"]["statements"] == [f'ALTER TABLE "public"."{made}" ADD COLUMN "budget" NUMERIC(10,2);']
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {
                "op": "alter_column", "column": "title", "to": {"name": "heading", "kind": "text", "length": 200, "nullable": True}}})
            assert len(reply["data"]["statements"]) == 4, reply
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {
                "op": "add_index", "name": "proj_heading_idx", "columns": ["heading"], "unique": False}})
            assert reply["success"], reply
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {"op": "drop_column", "column": "id"}})
            assert reply["error"]["details"] == [{"field": "column", "message": "key_column"}]
            _, reply = await owner.request("GET", f"{base}/structure", query={"schema": "public", "table": made})
            assert [c["name"] for c in reply["data"]["columns"]] == ["id", "heading", "budget"]
            assert any(i["name"] == "proj_heading_idx" for i in reply["data"]["indexes"])
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {"op": "drop_index", "name": "proj_heading_idx"}})
            assert reply["success"]
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": made, "change": {"op": "rename_table", "name": f"plans_{s}"}})
            assert reply["data"]["table"] == {"schema": "public", "name": f"plans_{s}"}
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": f"plans_{s}", "change": {"op": "truncate"}})
            assert reply["data"]["statements"] == [f'TRUNCATE TABLE "public"."plans_{s}";']
            _, reply = await owner.request("POST", change, body={"schema": "public", "table": f"plans_{s}", "change": {"op": "drop_table"}})
            assert reply["data"]["table"] is None
            assert await raw.fetchval("SELECT to_regclass($1)", f"public.plans_{s}") is None

            # Read only: no row changes, no structure changes
            await owner.request("PATCH", f"/datasources/{sid}", body={"access": {**ACCESS, "other": "read"}})
            _, reply = await owner.request("PATCH", f"{base}/rows", body={"schema": "public", "table": people, "key": "1", "values": {}})
            assert reply["error"]["code"] == "FRM-DEST-1019" and reply["error"]["details"][0]["message"] == "read_access"
            _, reply = await owner.request("POST", f"{base}/tables", body={"schema": "public", "name": made, "columns": spec})
            assert reply["error"]["code"] == "FRM-DEST-1019"
            await owner.request("PATCH", f"/datasources/{sid}", body={"enabled": False})
            _, reply = await owner.request("GET", f"{base}/tables")
            assert reply["error"]["code"] == "FRM-DEST-1009"

            _, trail = await owner.request("GET", "/audit-logs", query={"page_size": "100"})
            actions = {row["action"] for row in trail["data"]}
            assert {"data.row_inserted", "data.row_updated", "data.row_deleted", "data.user_table_created", "data.table_altered",
                    "data.table_truncated", "data.table_dropped"} <= actions

        stranger_sub, stranger_email = await new_workspace(app)
        async with client_for(app, host=f"{stranger_sub}.formalie.dev") as http:
            stranger = SecureClient(http)
            await sign_in(stranger, stranger_email, PASSWORD)
            _, reply = await stranger.request("GET", f"{base}/rows", query={"schema": "public", "table": people})
            assert reply["error"]["code"] == "FRM-GEN-1004"
    finally:
        for name in (people, teams, own, made, f"plans_{s}"):
            await raw.execute(f'DROP TABLE IF EXISTS public."{name}" CASCADE')
        await raw.close()
